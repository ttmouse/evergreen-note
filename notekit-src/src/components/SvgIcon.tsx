export type SvgIconName = keyof typeof iconMap
export const icons = Object.fromEntries(Object.keys(iconMap).map((key) => [key, key])) as { [K in SvgIconName]: K }

export function SvgIcon(props: { name?: SvgIconName; path?: string; width?: number; height?: number; color?: string }) {
  const { name, width = 16, height = 16, color } = props
  if (!name) {
    throw new Error('SvgIcon: name is required')
  }
  const PhosphorIcon = iconMap[name]
  const weight = name === 'svg_dot' ? 'fill' : 'regular'
  // Bullet 圆点：原版 roamedit 为 6px 实心点（--node-btn-default）；16px 圆形图标 × 0.45 ≈ 6px 视觉直径。
  // 折叠态节点按钮整体 scale(0.75)，乘上它声明的 --scale 补偿，折叠后的圆点才与展开时等大
  const style =
    name === 'svg_dot'
      ? { transform: 'scale(calc(0.45 * var(--scale, 1)))' }
      : undefined
  return <PhosphorIcon size={width} width={width} height={height} color={color} weight={weight} className="svg-icon" style={style} aria-hidden="true" />
}
